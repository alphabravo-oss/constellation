package main

import (
	"bytes"
	"encoding/base64"
	"errors"
	"fmt"
	"mime"
	"mime/multipart"
	"net/mail"
	"net/textproto"
	"strings"
)

type reportEmail struct {
	from, to string
	body     []byte
}

// Report metadata is operator-editable. Validate all header inputs before
// constructing MIME; never interpolate caller input into SMTP/header syntax.
func makeReportEmail(from, to, name, framework, signature, filename string, report []byte) (reportEmail, error) {
	for _, value := range []string{from, to, name, framework, signature, filename} {
		if strings.ContainsAny(value, "\r\n\x00") {
			return reportEmail{}, errors.New("email delivery: header contains control characters")
		}
	}
	sender, err := mail.ParseAddress(from)
	if err != nil {
		return reportEmail{}, errors.New("email delivery: invalid sender")
	}
	recipient, err := mail.ParseAddress(to)
	if err != nil {
		return reportEmail{}, errors.New("email delivery: invalid recipient")
	}
	var parts bytes.Buffer
	writer := multipart.NewWriter(&parts)
	text, err := writer.CreatePart(textproto.MIMEHeader{"Content-Type": {"text/plain; charset=utf-8"}})
	if err != nil {
		return reportEmail{}, err
	}
	if _, err = fmt.Fprintf(text, "Attached: %s\r\nFramework: %s\r\nGenerated by Constellation.\r\n", filename, framework); err != nil {
		return reportEmail{}, err
	}
	attachment, err := writer.CreatePart(textproto.MIMEHeader{
		"Content-Type":              {mime.FormatMediaType("application/octet-stream", map[string]string{"name": filename})},
		"Content-Disposition":       {mime.FormatMediaType("attachment", map[string]string{"filename": filename})},
		"Content-Transfer-Encoding": {"base64"},
	})
	if err != nil {
		return reportEmail{}, err
	}
	encoded := base64.StdEncoding.EncodeToString(report)
	for len(encoded) > 0 {
		end := min(len(encoded), 76)
		if _, err = fmt.Fprintf(attachment, "%s\r\n", encoded[:end]); err != nil {
			return reportEmail{}, err
		}
		encoded = encoded[end:]
	}
	if err = writer.Close(); err != nil {
		return reportEmail{}, err
	}
	var message strings.Builder
	message.WriteString("From: " + sender.String() + "\r\n")
	message.WriteString("To: " + recipient.String() + "\r\n")
	message.WriteString("Subject: " + mime.QEncoding.Encode("UTF-8", "Compliance report — "+name+" ("+framework+")") + "\r\n")
	if signature != "" {
		message.WriteString("X-Constellation-Cosign-Signature: " + signature + "\r\n")
	}
	message.WriteString("MIME-Version: 1.0\r\n")
	message.WriteString("Content-Type: " + mime.FormatMediaType("multipart/mixed", map[string]string{"boundary": writer.Boundary()}) + "\r\n\r\n")
	message.Write(parts.Bytes())
	return reportEmail{from: sender.Address, to: recipient.Address, body: []byte(message.String())}, nil
}
